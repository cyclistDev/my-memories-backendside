CREATE TABLE resurfacing_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    memory_id BIGINT NOT NULL,
    surfaced_date DATE NOT NULL,
    CONSTRAINT fk_resurfacing_history_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_resurfacing_history_memory FOREIGN KEY (memory_id) REFERENCES memories (id) ON DELETE CASCADE,
    CONSTRAINT uk_resurfacing_history_user_date UNIQUE (user_id, surfaced_date)
);
