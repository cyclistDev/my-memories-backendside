CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_tags_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_tags_user_name UNIQUE (user_id, name)
);

CREATE TABLE memory_tags (
    memory_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,
    CONSTRAINT pk_memory_tags PRIMARY KEY (memory_id, tag_id),
    CONSTRAINT fk_memory_tags_memory FOREIGN KEY (memory_id) REFERENCES memories (id),
    CONSTRAINT fk_memory_tags_tag FOREIGN KEY (tag_id) REFERENCES tags (id)
);

CREATE INDEX idx_tags_user ON tags (user_id);
CREATE INDEX idx_memory_tags_tag ON memory_tags (tag_id);
